import * as fs from "node:fs"
import * as path from "node:path"
import { describe, expect, it } from "vitest"

const root = process.cwd()
const read = (file: string) => fs.readFileSync(path.join(root, file))

/** Width, height and colour type from a PNG's IHDR chunk. */
function pngHeader(file: string): {
  width: number
  height: number
  colourType: number
} {
  const png = read(file)
  expect(png.subarray(1, 4).toString()).toBe("PNG")
  return {
    width: png.readUInt32BE(16),
    height: png.readUInt32BE(20),
    colourType: png.readUInt8(25),
  }
}

const RGBA = 6

// These files are generated by `pnpm brand:render`; if this fails, re-run it and commit the output.
describe("Brand assets (generated by scripts/render-brand-assets.mjs)", () => {
  describe("Given the oak cut out of the supplied logo", () => {
    const oak = pngHeader("src/assets/brand/oak.png")

    it("Then it is square, so it can stand in for the mark at any size", () => {
      expect(oak.width).toBe(oak.height)
    })

    it("Then it is large enough for the hero at 3x", () => {
      expect(oak.width).toBeGreaterThanOrEqual(1200)
    })

    it("Then it has an alpha channel, so it sits on paper and stone alike", () => {
      expect(oak.colourType).toBe(RGBA)
    })
  })

  describe("Given the raster images", () => {
    it.each([
      ["public/apple-touch-icon.png", 180, 180],
      ["public/brand/logo-512.png", 512, 512],
      ["public/og/default.png", 1200, 630],
    ])("Then %s is %i × %i", (file, width, height) => {
      const png = pngHeader(file)
      expect([png.width, png.height]).toEqual([width, height])
    })

    it("Then favicon.ico holds 16, 32 and 48 px images", () => {
      const ico = read("public/favicon.ico")
      const count = ico.readUInt16LE(4)
      const sizes = Array.from({ length: count }, (_, i) =>
        ico.readUInt8(6 + 16 * i),
      )
      expect(sizes).toEqual([16, 32, 48])
    })
  })
})
